%getPipelineWindowPosition Center a resizable pipeline window on its monitor.

function position = getPipelineWindowPosition( ...
    widthFraction, heightFraction, minWidth, minHeight)

arguments
    widthFraction (1,1) double {mustBeGreaterThan(widthFraction, 0), ...
        mustBeLessThanOrEqual(widthFraction, 1)} = 0.90
    heightFraction (1,1) double {mustBeGreaterThan(heightFraction, 0), ...
        mustBeLessThanOrEqual(heightFraction, 1)} = 0.88
    minWidth (1,1) double {mustBePositive} = 900
    minHeight (1,1) double {mustBePositive} = 600
end

monitorPositions = get(groot, 'MonitorPositions');
pointerLocation = get(groot, 'PointerLocation');

monitorIndex = find( ...
    pointerLocation(1) >= monitorPositions(:, 1) & ...
    pointerLocation(1) <= monitorPositions(:, 1) + monitorPositions(:, 3) & ...
    pointerLocation(2) >= monitorPositions(:, 2) & ...
    pointerLocation(2) <= monitorPositions(:, 2) + monitorPositions(:, 4), ...
    1);

if isempty(monitorIndex)
    monitorIndex = 1;
end

monitor = monitorPositions(monitorIndex, :);
margin = 20;
availableWidth = max(1, monitor(3) - 2 * margin);
availableHeight = max(1, monitor(4) - 2 * margin);

windowWidth = min(max(round(monitor(3) * widthFraction), minWidth), ...
    availableWidth);
windowHeight = min(max(round(monitor(4) * heightFraction), minHeight), ...
    availableHeight);

position = [ ...
    monitor(1) + floor((monitor(3) - windowWidth) / 2), ...
    monitor(2) + floor((monitor(4) - windowHeight) / 2), ...
    windowWidth, ...
    windowHeight];
end