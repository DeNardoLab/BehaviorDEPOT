function [roiLimits, roiName, confirmed] = drawROIWithName( ...
        frame, dialogTitle, previousROIs, initialName, nameEditable)
%drawROIWithName Draw one ROI and edit or review its name in one panel.
%
% A conventional figure and axes are used here instead of a uiaxes in a
% uigridlayout. Interactive image ROI objects can retain a stale screen to
% image transform when that combination is resized.

arguments
    frame
    dialogTitle (1,:) char
    previousROIs cell
    initialName (1,:) char
    nameEditable (1,1) logical
end

roiLimits = [];
roiName = initialName;
confirmed = false;
currentROI = [];
wasCanceled = false;

roiFigure = figure( ...
    'Name', dialogTitle, ...
    'NumberTitle', 'off', ...
    'MenuBar', 'none', ...
    'ToolBar', 'none', ...
    'WindowStyle', 'modal', ...
    'Position', getPipelineWindowPosition(0.90, 0.88, 900, 600), ...
    'Resize', 'on', ...
    'CloseRequestFcn', @cancelAnalysis);

imagePanel = uipanel(roiFigure, ...
    'Title', 'Video Frame', ...
    'Units', 'normalized', ...
    'Position', [0.02 0.12 0.67 0.85]);
roiAxes = axes(imagePanel, ...
    'Units', 'normalized', ...
    'Position', [0.03 0.03 0.94 0.94], ...
    'PositionConstraint', 'innerposition');
showROIFrame(roiAxes, frame, previousROIs);

controlPanel = uipanel(roiFigure, ...
    'Title', 'ROI Controls', ...
    'Units', 'normalized', ...
    'Position', [0.71 0.12 0.27 0.85]);

uicontrol(controlPanel, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.08 0.79 0.84 0.16], ...
    'HorizontalAlignment', 'left', ...
    'String', { ...
        'Draw the polygon on the full video frame.', ...
        'Adjust vertices directly on the image,', ...
        'delete the selection, or redraw it before confirming.'});
uicontrol(controlPanel, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.08 0.69 0.84 0.05], ...
    'HorizontalAlignment', 'left', ...
    'String', 'ROI name');

if nameEditable
    nameControl = uicontrol(controlPanel, ...
        'Style', 'edit', ...
        'Units', 'normalized', ...
        'Position', [0.08 0.63 0.84 0.07], ...
        'String', initialName);
else
    nameControl = uicontrol(controlPanel, ...
        'Style', 'text', ...
        'Units', 'normalized', ...
        'Position', [0.08 0.63 0.84 0.07], ...
        'HorizontalAlignment', 'left', ...
        'FontWeight', 'bold', ...
        'String', initialName);
end

drawButton = uicontrol(controlPanel, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.08 0.49 0.84 0.09], ...
    'String', 'Draw ROI', ...
    'Callback', @drawROI);
deleteButton = uicontrol(controlPanel, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.08 0.38 0.84 0.09], ...
    'String', 'Delete Current ROI', ...
    'Enable', 'off', ...
    'Callback', @deleteCurrentROI);

uicontrol(roiFigure, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.02 0.025 0.47 0.065], ...
    'String', 'Cancel Analysis', ...
    'Callback', @cancelAnalysis);
uicontrol(roiFigure, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.51 0.025 0.47 0.065], ...
    'String', 'Confirm ROI', ...
    'Callback', @confirmROI);

waitfor(roiFigure);

if wasCanceled
    error('BehaviorDEPOT:drawROIWithName:AnalysisCanceled', ...
        'The analysis run was canceled during ROI selection.');
end

    function drawROI(~, ~)
        deleteCurrentROI([], []);
        drawnow;
        currentROI = drawpolygon(roiAxes, 'DrawingArea', 'auto');

        if isvalid(currentROI) && ~isempty(currentROI.Position)
            set(drawButton, 'String', 'Redraw ROI');
            set(deleteButton, 'Enable', 'on');
        else
            currentROI = [];
        end
    end

    function deleteCurrentROI(~, ~)
        if ~isempty(currentROI) && isvalid(currentROI)
            delete(currentROI);
        end
        currentROI = [];
        set(drawButton, 'String', 'Draw ROI');
        set(deleteButton, 'Enable', 'off');
    end

    function confirmROI(~, ~)
        if isempty(currentROI) || ~isvalid(currentROI) || ...
                isempty(currentROI.Position)
            errordlg('Draw an ROI before confirming.', 'ROI Required', 'modal');
            return
        end

        if nameEditable
            cleanedName = cleanText({get(nameControl, 'String')});
            roiName = cleanedName{1};
            if isempty(roiName)
                errordlg('Enter an ROI name before confirming.', ...
                    'ROI Name Required', 'modal');
                return
            end
        end

        roiLimits = currentROI.Position;
        confirmed = true;
        delete(roiFigure);
    end

    function cancelAnalysis(~, ~)
        wasCanceled = true;
        delete(roiFigure);
    end
end
